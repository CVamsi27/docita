-- Referral partner self-service portal (additive only, schema-locked).
--
-- What this migration adds:
--   1. Referrer.code         -- human-shareable `RFR-XXXXXX`. Nullable for
--                                back-compat with existing rows; backfilled
--                                by `scripts/db/backfill-referrer-codes.ts`.
--   2. Referrer.welcomeSentAt, Referrer.welcomeError -- last welcome-send
--                                status for operator visibility.
--   3. ReferrerPayoutDetails -- 1:1 banking / payout info. AES-GCM encrypted
--                                IFSC + account number + optional PAN, plus
--                                last-4 + plaintext IFSC for display/audit.
--   4. ReferrerMessage       -- message audit log (welcome, resend, payout).
--   5. Two new enums.
--
-- Why hand-authored (not generated by `prisma migrate dev`):
--   - Schema-locked project-wide rule. This migration is strictly additive.
--   - Generated migrations from `migrate dev` can include non-additive
--     noise (sequence ownership, comment rewrites) that breaks the lock.
--   - We diff against the file at commit time before merge.
--
-- Diff is the new migration under `prisma/migrations/20260727120000_*/`
-- vs the previous migration `20260715100000_normalize_patient_phone_to_e164`.

-- 1. Enums
CREATE TYPE "ReferrerMessageKind" AS ENUM ('WELCOME', 'RESEND_WELCOME', 'PAYOUT_NOTICE');
CREATE TYPE "ReferrerMessageStatus" AS ENUM ('QUEUED', 'SENT', 'FAILED');

-- 2. Extend Referrer
ALTER TABLE "Referrer" ADD COLUMN "code" TEXT;
ALTER TABLE "Referrer" ADD COLUMN "welcomeSentAt" TIMESTAMPTZ(3);
ALTER TABLE "Referrer" ADD COLUMN "welcomeError" TEXT;
CREATE UNIQUE INDEX "Referrer_code_key" ON "Referrer"("code");

-- 3. ReferrerPayoutDetails
CREATE TABLE "ReferrerPayoutDetails" (
    "id" TEXT NOT NULL,
    "referrerId" TEXT NOT NULL,
    "accountHolder" TEXT NOT NULL,
    "accountNumberEnc" TEXT NOT NULL,
    "accountNumberLast4" TEXT NOT NULL,
    "ifscEnc" TEXT NOT NULL,
    "ifscPlain" TEXT NOT NULL,
    "bankName" TEXT NOT NULL,
    "upiId" TEXT,
    "panEnc" TEXT,
    "panLast4" TEXT,
    "verified" BOOLEAN NOT NULL DEFAULT false,
    "verifiedByAdminId" TEXT,
    "verifiedAt" TIMESTAMPTZ(3),
    "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMPTZ(3) NOT NULL,
    CONSTRAINT "ReferrerPayoutDetails_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "ReferrerPayoutDetails_referrerId_key" ON "ReferrerPayoutDetails"("referrerId");
CREATE INDEX "ReferrerPayoutDetails_verified_idx" ON "ReferrerPayoutDetails"("verified");
ALTER TABLE "ReferrerPayoutDetails" ADD CONSTRAINT "ReferrerPayoutDetails_referrerId_fkey"
    FOREIGN KEY ("referrerId") REFERENCES "Referrer"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- 4. ReferrerMessage
CREATE TABLE "ReferrerMessage" (
    "id" TEXT NOT NULL,
    "referrerId" TEXT NOT NULL,
    "kind" "ReferrerMessageKind" NOT NULL,
    "channel" TEXT NOT NULL DEFAULT 'whatsapp',
    "template" TEXT NOT NULL,
    "status" "ReferrerMessageStatus" NOT NULL DEFAULT 'QUEUED',
    "externalId" TEXT,
    "errorMessage" TEXT,
    "payload" JSONB NOT NULL,
    "createdAt" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "sentAt" TIMESTAMPTZ(3),
    CONSTRAINT "ReferrerMessage_pkey" PRIMARY KEY ("id")
);
CREATE INDEX "ReferrerMessage_referrerId_createdAt_idx" ON "ReferrerMessage"("referrerId", "createdAt");
CREATE INDEX "ReferrerMessage_status_idx" ON "ReferrerMessage"("status");
ALTER TABLE "ReferrerMessage" ADD CONSTRAINT "ReferrerMessage_referrerId_fkey"
    FOREIGN KEY ("referrerId") REFERENCES "Referrer"("id") ON DELETE CASCADE ON UPDATE CASCADE;
